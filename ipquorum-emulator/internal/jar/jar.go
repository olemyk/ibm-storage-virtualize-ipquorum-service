// Package jar builds the per-cluster ip_quorum.jar served by the emulator.
//
// The real ip_quorum.jar embeds the node list of the system it was created on.
// The emulator does the same: it takes a template JAR (the fake ip_quorum.jar
// built from fake-ipquorum-jar/) and adds a quorum.properties entry listing
// the cluster's node addresses.
package jar

import (
	"archive/zip"
	"bytes"
	"fmt"
	"io"
	"os"
	"strings"
	"sync"

	"github.com/olemyk/ipquorum-emulator/internal/config"
)

// ConfigEntry is the name of the entry that holds the per-cluster config.
const ConfigEntry = "quorum.properties"

// Builder creates cluster specific JARs from a template. It implements
// rest.JARSource.
type Builder struct {
	template []byte

	mu    sync.Mutex
	cache map[string][]byte
}

// NewBuilder creates a Builder from template JAR bytes.
func NewBuilder(template []byte) (*Builder, error) {
	zr, err := zip.NewReader(bytes.NewReader(template), int64(len(template)))
	if err != nil {
		return nil, fmt.Errorf("template is not a valid jar/zip: %w", err)
	}
	for _, f := range zr.File {
		if f.Name == ConfigEntry {
			return nil, fmt.Errorf("template already contains %s", ConfigEntry)
		}
	}
	return &Builder{template: template, cache: map[string][]byte{}}, nil
}

// NewBuilderFromFile reads the template JAR from disk.
func NewBuilderFromFile(path string) (*Builder, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read template jar: %w", err)
	}
	return NewBuilder(data)
}

// Build returns a JAR whose embedded node list matches the cluster.
func (b *Builder) Build(cl config.Cluster) ([]byte, error) {
	props := Properties(cl)

	b.mu.Lock()
	defer b.mu.Unlock()
	if out, ok := b.cache[props]; ok {
		return out, nil
	}

	zr, err := zip.NewReader(bytes.NewReader(b.template), int64(len(b.template)))
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	zw := zip.NewWriter(&buf)
	for _, f := range zr.File {
		// Preserve entries and their order: java -jar expects the manifest first.
		w, err := zw.CreateHeader(&zip.FileHeader{Name: f.Name, Method: f.Method, Modified: f.Modified})
		if err != nil {
			return nil, err
		}
		if f.FileInfo().IsDir() {
			continue
		}
		rc, err := f.Open()
		if err != nil {
			return nil, err
		}
		_, err = io.Copy(w, rc)
		rc.Close()
		if err != nil {
			return nil, err
		}
	}
	w, err := zw.Create(ConfigEntry)
	if err != nil {
		return nil, err
	}
	if _, err := io.WriteString(w, props); err != nil {
		return nil, err
	}
	if err := zw.Close(); err != nil {
		return nil, err
	}

	out := buf.Bytes()
	b.cache[props] = out
	return out, nil
}

// Properties renders the quorum.properties content for a cluster.
func Properties(cl config.Cluster) string {
	addrs := make([]string, len(cl.Nodes))
	for i, n := range cl.Nodes {
		addrs[i] = n.Address
	}
	return fmt.Sprintf("# generated by ipquorum-emulator\nsystem=%s\nnodes=%s\n", cl.Name, strings.Join(addrs, ","))
}
